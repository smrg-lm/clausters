//! Audio-bus I/O.
//!
//! One slice of the catalog, in its place in the table order;
//! `super::FAMILIES` concatenates them all.

use super::*;

pub(super) static UGENS: &[UGenDescriptor] = &[
    // --- audio-bus I/O (audio rate only; carries a bus role) ---
    desc(
        "In",
        Fixed(1),
        I_BUS,
        Ar,
        R_AR,
        Normal,
        Read,
        false,
        |_, _| Box::new(In),
    ),
    desc(
        "InCtl",
        Fixed(1),
        I_BUS,
        Ar,
        R_AR,
        Normal,
        BusRole::ReadControl,
        false,
        |_, _| Box::new(InCtl),
    ),
    desc(
        "OutCtl",
        Fixed(2),
        I_BUS_SIGNAL,
        Ar,
        R_AR,
        Normal,
        BusRole::WriteControl,
        false,
        |_, _| Box::new(OutCtl),
    ),
    desc(
        "Out",
        Fixed(2),
        I_BUS_SIGNAL,
        Ar,
        R_AR,
        Normal,
        Write,
        false,
        |_, _| Box::new(Out),
    ),
    desc(
        "ReplaceOut",
        Fixed(2),
        I_BUS_SIGNAL,
        Ar,
        R_AR,
        Normal,
        ReadWrite,
        false,
        |_, _| Box::new(ReplaceOut),
    ),
    // --- scsynth's other bus readers and writers ---
    desc(
        "InFeedback",
        Fixed(1),
        I_BUS,
        Ar,
        R_AR,
        Normal,
        Read,
        false,
        |_, _| Box::new(InFeedback),
    ),
    // An `Out`: a synth starts at its bundle's sample here, so there is no
    // offset into its first block to make up.
    desc(
        "OffsetOut",
        Fixed(2),
        I_BUS_SIGNAL,
        Ar,
        R_AR,
        Normal,
        Write,
        false,
        |_, _| Box::new(Out),
    ),
    desc(
        "XOut",
        Fixed(3),
        &[inp("bus", 0.0), inp("xfade", 1.0), inp("signal", 0.0)],
        Ar,
        R_AR,
        Normal,
        ReadWrite,
        false,
        |_, _| Box::new(XOut::default()),
    ),
    desc(
        "InTrig",
        Fixed(1),
        I_BUS,
        Kr,
        R_KR,
        Normal,
        BusRole::ReadControl,
        false,
        |_, _| Box::new(InTrig::default()),
    ),
    desc(
        "LagIn",
        Fixed(2),
        &[inp("bus", 0.0), inp("lag", 0.1)],
        Kr,
        R_KR,
        Normal,
        BusRole::ReadControl,
        false,
        |_, _| Box::new(LagIn::default()),
    ),
    // The control buses are what scsynth's shared controls are here: memory
    // a client in another process maps.
    desc(
        "SharedIn",
        Fixed(1),
        I_BUS,
        Kr,
        R_KR,
        Normal,
        BusRole::ReadControl,
        false,
        |_, _| Box::new(InCtl),
    ),
    desc(
        "SharedOut",
        Fixed(2),
        I_BUS_SIGNAL,
        Kr,
        R_KR,
        Normal,
        BusRole::WriteControl,
        false,
        |_, _| Box::new(OutCtl),
    ),
];
