// Writes `licenses/THIRD-PARTY.txt`: the license of every third-party work
// the editor ships, which most of those licenses ask to travel with the
// copies. Read from what is actually shipped rather than from a list:
//
// - the page (page/): its npm dependencies, which its bundle and its files
//   carry whole (the session's parser, TypeScript and its library
//   declarations);
// - the faces the GUI host embeds in the binary, with their licenses as the
//   host keeps them (crates/clausters-gui-draw/assets/fonts);
// - the engraver's library, libverovio, which the binary links and the wheel
//   carries beside it;
// - the binary: the crates `cargo about` resolves for every release target,
//   configured by `about.toml` and rendered by `about.hbs`.
//
// Identical license texts are written once, with every package that uses it.
//
//   node scripts/notices.mjs           write the file
//   node scripts/notices.mjs --check   fail if it is not current
//
// Needs the page's dependencies installed (`npm ci` in page/) and `cargo
// about` at the version CI pins.

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..", "..");
const page = join(root, "page");
const out = join(root, "licenses", "THIRD-PARTY.txt");
const rule = "-".repeat(80);

/** The license files a package directory carries. */
function licenseFiles(dir) {
  return readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)/i.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8").trim());
}

/** The page's npm dependencies, each with its license, identical texts once. */
function pagePackages() {
  const deps = JSON.parse(readFileSync(join(page, "package.json"), "utf8")).dependencies ?? {};
  const byText = new Map();
  for (const name of Object.keys(deps).sort()) {
    const dir = join(page, "node_modules", name);
    if (!existsSync(dir)) throw new Error(`${name} is not installed: run npm ci in page/`);
    const meta = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const texts = licenseFiles(dir);
    if (texts.length === 0) throw new Error(`no license file in: ${name}`);
    const text = texts.join("\n\n");
    const users = byText.get(text) ?? [];
    users.push(`${name} ${meta.version} (${meta.license ?? "see below"})`);
    byText.set(text, users);
  }
  return [...byText]
    .map(([text, users]) => `${rule}\nUsed by:\n${users.map((u) => `  ${u}\n`).join("")}\n${text}\n`)
    .join("\n");
}

/** The faces the host embeds: their notices, as the host keeps them. */
function fonts() {
  const dir = join(repo, "crates", "clausters-gui-draw", "assets", "fonts");
  return ["OFL.txt", "LICENSE"]
    .map((name) => `${rule}\n${readFileSync(join(dir, name), "utf8").trim()}\n`)
    .join("\n");
}

/** libverovio's license (LGPL-3.0), from the pinned source it is built from. */
function verovio() {
  const text = readFileSync(join(repo, "third_party", "verovio", "COPYING.LESSER"), "utf8").trim();
  return `${rule}\nUsed by:\n  libverovio (LGPL-3.0-only), https://www.verovio.org/\n\n${text}\n`;
}

/** The binary's crates, by license, but the project's own: a section used
 *  only by `clausters` crates is the project's license, not a third party's. */
function binary() {
  const generated = execFileSync("cargo", ["about", "generate", "--locked", "about.hbs"], {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });
  return generated
    .split(`${rule}\n`)
    .filter((section) => {
      const users = section.split("\n\n")[0].split("\n").slice(1).map((l) => l.trim()).filter(Boolean);
      const own = (u) => /^clausters(-[a-z-]+)? /.test(`${u} `);
      return section.trim() !== "" && !users.every(own);
    })
    .map((section) => `${rule}\n${section}`)
    .join("")
    .trim();
}

const text = [
  "Third-party software in clausters-editor",
  "",
  "The licenses of the works this application is built with, as they ship",
  "in it. Generated by scripts/notices.mjs; do not edit by hand.",
  "",
  "",
  "PART 1 -- THE PAGE (the JavaScript the editor's page carries)",
  "",
  pagePackages(),
  "",
  "PART 2 -- THE FACES (the fonts the GUI host draws with, in the binary)",
  "",
  fonts(),
  "",
  "PART 3 -- THE ENGRAVER (libverovio, which the binary links)",
  "",
  verovio(),
  "",
  "PART 4 -- THE APPLICATION BINARY (Rust crates, every release platform)",
  "",
  binary(),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== text) {
    console.error("licenses/THIRD-PARTY.txt is not current: run `node scripts/notices.mjs`");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
