#!/usr/bin/env python3
"""``edit(node)``: a running node's controls in a window nobody wrote.

A SynthDef declares how each control is drawn where it declares the control --
a range, a step, a warp, a unit -- and ``edit`` opens any node of it with a
window of those controls, generated by the shared core and kept by the GUI
host. A control that declares nothing is drawn too: a conventional name
(``amp``) has its usual range, and any other a range around its default.

What to do in the window:

- **drag a slider**: the node changes at once, with no round trip through
  this script -- each widget is bound to its control on the server;
- **click the toggle** to stop the vibrato and start it again;
- watch the value beside each control: it is the server's own text for it,
  number and unit;
- **type in the search field** (``rate``, ``hz``) and only the controls
  whose name holds it are shown; a def of many controls is paged as well.

The second cell changes the node **from this script**, and the window follows:
the host reads every binding back from the server, so a value changes in the
window whoever changed it -- this script, another client, a plugin's own
window.

Run it as a script, or step through the cells::

    python clients/python/examples/editors/edit_node.py

It boots an audio server and the GUI host; it needs a display and an audio
device. The paired page is ``clients/web/examples/editors/edit-node.html``.
"""

# %%
import sys

from clausters import Session, Synth, SynthDef
from clausters.defs import control, out, sine
from clausters.defs.ugens import lpf, pan2, saw
from clausters.gui import edit

session = Session.live()
server = session.server

# %% [markdown]
# ## A def that says how its controls are drawn
#
# ``freq`` and ``rate`` travel by ratios (``warp="exp"``), ``vibrato`` is a
# switch (a step of one over ``0..1``), ``amp`` declares nothing and gets the
# range its name conventionally has, and ``bright`` declares nothing at all.

# %%
freq = control("freq", 660.0, min=220.0, max=1760.0, warp="exp", unit="Hz")
rate = control("rate", 5.0, min=0.5, max=12.0, warp="exp", unit="Hz")
depth = control("depth", 6.0, min=0.0, max=40.0, unit="Hz")
vibrato = control("vibrato", 1.0, min=0.0, max=1.0, step=1.0)
amp = control("amp", 0.06)
bright = control("bright", 3.0)

pitch = freq + sine(rate) * depth * vibrato
tone = lpf(saw(pitch), pitch * bright) * amp
SynthDef("edit_node_tone", out(0.0, pan2(tone))).send(server)
node = Synth("edit_node_tone", server=server)
server.sync()

# %% [markdown]
# ## One verb
#
# The window is up when this returns, and the host keeps it: nothing here
# answers a slider.

# %%
editor = edit(node)

# %% [markdown]
# ## The window follows the node
#
# A ``/node_set`` from this script moves the slider and the text beside it
# within a moment; ``get_text`` asks the server for the same text the window
# shows.

# %%
node.set({"freq": 880.0, "depth": 12.0})
print(node.get_text("freq", "depth"))

# %%
if __name__ == "__main__" and not hasattr(sys, "ps1"):
    try:
        editor.wait()
    finally:
        node.free()
        session.close()
else:
    print("editor open -- editor.search('rate'), node.set({...}); session.close() to end")
